def privacy_tests() -> list[dict]:
    out = []
    for name, text, must_go, must_stay in PRIVACY_SAMPLES:
        clean, found = redact_sensitive(text)
        ok = (must_go is None or must_go not in clean) and (must_stay is None or must_stay in clean)
        out.append({"case": name, "input": text, "output": clean, "detected": found, "ok": ok})
    return out


def environment() -> tuple[str, list[str]]:
    """Which interpreter and optional packages this run actually used."""
    import importlib.metadata as im
    import platform

    def ver(pkg):
        try:
            return im.version(pkg)
        except im.PackageNotFoundError:
            return None

    line = f"Python {platform.python_version()} · fpdf2 {ver('fpdf2') or 'NOT INSTALLED'} · uharfbuzz {ver('uharfbuzz') or 'NOT INSTALLED'}"
    warnings = []
    if not ver("uharfbuzz"):
        warnings.append("uharfbuzz is not installed: Hindi PDFs were generated WITHOUT text shaping (conjuncts may render "
                        "incorrectly). The text checks are unaffected. Run `pip install -r requirements.txt`.")
    return line, warnings


def main():
    env_line, env_warnings = environment()
    print("Environment:", env_line)
    for w in env_warnings:
        print("WARNING:", w)
    data = json.loads((ROOT / "tests" / "test_cases.json").read_text(encoding="utf-8"))
    today = date.fromisoformat(data["reference_date"])
    for d in (RAW_OUTPUTS_DIR, COMPLAINTS_DIR):
        if d.exists():
            shutil.rmtree(d)
        d.mkdir(parents=True, exist_ok=True)
    summary = []
    for spec in data["cases"]:
        folder = RAW_OUTPUTS_DIR / f"{spec['id']}_{spec['slug']}"
        (folder / "documents").mkdir(parents=True, exist_ok=True)
        state, unscripted = run_intake(spec, today)
        result = run_from_intake(state, today, lang=spec["language"])
        extra_docs = None
        if spec["language"] != "en":
            en = run_from_intake(state, today, lang="en")
            extra_docs = {f"{k}_en": v for k, v in en["documents"].items()}
        (folder / "conversation.md").write_text(transcript_md(state), encoding="utf-8")
        (folder / "intake_state.json").write_text(json.dumps(state, ensure_ascii=False, indent=2), encoding="utf-8")
        (folder / "case_file.json").write_text(json.dumps(result["case"], ensure_ascii=False, indent=2, default=str), encoding="utf-8")
        (folder / "rights_analysis.json").write_text(json.dumps(result["rights"], ensure_ascii=False, indent=2), encoding="utf-8")
        (folder / "rights_analysis.md").write_text(rights_md(result["rights"]), encoding="utf-8")
        (folder / "action_plan.json").write_text(json.dumps(result["plan"], ensure_ascii=False, indent=2), encoding="utf-8")
        (folder / "action_plan.md").write_text(plan_md(result["plan"]), encoding="utf-8")
        all_docs = {f"{k}_{spec['language']}": v for k, v in result["documents"].items()}
        all_docs.update(extra_docs or {})
        for k, d in all_docs.items():
            (folder / "documents" / f"{k}.txt").write_text(d["text"], encoding="utf-8")
            pdf = text_to_pdf(d["text"], d["title"], d["language"])
            (COMPLAINTS_DIR / f"{spec['id']}_{k}.pdf").write_bytes(pdf)
        checks = check_case(spec, result, extra_docs, unscripted)
        (folder / "automated_checks.json").write_text(json.dumps(checks, ensure_ascii=False, indent=2, default=str), encoding="utf-8")
        summary.append({"spec": spec, "checks": checks})
        print(f"{spec['id']}: category {checks['category_actual']} ({'ok' if checks['category_ok'] else 'WRONG'}), "
              f"fields {checks['fields_correct']}/{checks['fields_total']}, citations valid={checks['all_citations_valid']}, "
              f"checks {checks['automated_checks_passed']}/{checks['automated_checks_total']}, unscripted={unscripted}")
    retr = retrieval_tests()
    (RAW_OUTPUTS_DIR / "retrieval_probe_test.json").write_text(json.dumps(retr, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"retrieval probes: top-1 {sum(r['top1_ok'] for r in retr)}/{len(retr)}, top-3 {sum(r['top3_ok'] for r in retr)}/{len(retr)}")
    for r in retr:
        if not r["top1_ok"]:
            print(f"   top-1 miss: {r['question']} -> {r['top3']} (acceptable {r['acceptable']})")
    hall = hallucination_tests(today)
    priv = privacy_tests()
    claims = claim_path_tests(today)
    (RAW_OUTPUTS_DIR / "claim_amount_test.json").write_text(json.dumps(claims, ensure_ascii=False, indent=2), encoding="utf-8")
    for c in claims:
        print(f"claim path {c['path']}: asked {c['times_asked']}x -> {c['claim']['amount']} ({c['claim']['basis'] or 'unconfirmed'}) "
              f"-> {'ok' if c['ok'] else 'FAIL ' + '; '.join(c['draft_problems'])}")
    (RAW_OUTPUTS_DIR / "hallucination_injection_test.json").write_text(json.dumps(hall, ensure_ascii=False, indent=2), encoding="utf-8")
    (RAW_OUTPUTS_DIR / "privacy_redaction_test.json").write_text(json.dumps(priv, ensure_ascii=False, indent=2), encoding="utf-8")
    for h in hall:
        print(f"hallucination test {h['scenario']}: expected_accept={h['expected_accept']} accepted={h['accepted']} -> {'ok' if h['ok'] else 'FAIL'}")
    for p in priv:
        print(f"privacy: {p['case']}: {'ok' if p['ok'] else 'FAIL'}  -> {p['output']}")
    # combined machine-readable + readable summary
    combined = {"reference_date": data["reference_date"], "cases": [s["checks"] for s in summary],
                "hallucination_injection": hall, "privacy_redaction": priv, "retrieval_probes": retr, "claim_amount_paths": claims}
    (RAW_OUTPUTS_DIR / "automated_checks.json").write_text(json.dumps(combined, ensure_ascii=False, indent=2, default=str), encoding="utf-8")
    md = ["# Automated checks (generated by tests/run_tests.py)", "", f"Reference date: {data['reference_date']} · Mode: demo (deterministic, no LLM API)", "",
          f"Environment: {env_line}", "", *[f"**Warning:** {w}" for w in env_warnings], *([""] if env_warnings else []),
          "| Case | Category | Fields extracted | Required sources | Citations valid | Refund claimed in every draft | Docs [MISSING] counts | Automated checks |",
          "|---|---|---|---|---|---|---|---|"]
    for s in summary:
        c = s["checks"]
        md.append(f"| {c['id']} | {c['category_actual']} {'✓' if c['category_ok'] else '✗'} | {c['fields_correct']}/{c['fields_total']} | "
                  f"{'✓' if not c['missing_required_sources'] else '✗ missing ' + ', '.join(c['missing_required_sources'])} | "
                  f"{'✓' if c['all_citations_valid'] else '✗'} | "
                  f"{(format_inr(c['claim_amount']['actual']['amount']) if c['claim_amount']['actual']['amount'] else ('not requested' if not c['claim_amount']['actual']['refund_requested'] else '[MISSING]'))} "
                  f"{'✓' if c['claim_amount']['ok'] else '✗ ' + '; '.join(c['claim_amount']['problems'])} | {', '.join(f'{k.split(chr(95))[0]}:{v}' for k, v in c['doc_missing_counts'].items())} | "
                  f"{c['automated_checks_passed']}/{c['automated_checks_total']} |")
    md += ["", "## Field-level extraction results", ""]
    for s in summary:
        c = s["checks"]
        md.append(f"### {c['id']}")
        for path, v in c["fields"].items():
            md.append(f"- {'✓' if v['ok'] else '✗'} `{path}` expected `{v['expected']}` got `{v['actual']}`")
        if c["unscripted_questions_skipped"]:
            md.append(f"- Questions the harness had no scripted answer for (skipped): {', '.join(c['unscripted_questions_skipped'])}")
        md.append("")
    md += ["## Hallucination-injection test (fake LLM)", "", "| Scenario | Should be accepted | Accepted | Result |", "|---|---|---|---|"]
    md += [f"| {h['scenario']} | {h['expected_accept']} | {h['accepted']} | {'✓' if h['ok'] else '✗'} |" for h in hall]
    md += ["", f"## Retrieval probes (question box) — top-1 {sum(r['top1_ok'] for r in retr)}/{len(retr)}, top-3 {sum(r['top3_ok'] for r in retr)}/{len(retr)}", "",
           "| Question | Acceptable | Top 3 retrieved | Top-1 |", "|---|---|---|---|"]
    md += [f"| {r['question']} | {', '.join(r['acceptable'])} | {', '.join(r['top3'])} | {'✓' if r['top1_ok'] else '✗'} |" for r in retr]
    md += ["", f"## Claimed-amount paths — {sum(c['ok'] for c in claims)}/{len(claims)}", "",
           "| Path | Answers given | Times asked | Claim recorded | Relief line in platform complaint | Result |", "|---|---|---|---|---|---|"]
    md += [f"| {c['path']} | {' / '.join(c['answers'])} | {c['times_asked']} | "
           f"{format_inr(c['claim']['amount']) + ' (' + c['claim']['basis'] + ')' if c['claim']['amount'] else 'not confirmed'} | "
           f"{(c['relief_line'] or ['—'])[0]} | {'✓' if c['ok'] else '✗'} |" for c in claims]
    md += ["", f"## Privacy redaction test — {sum(p['ok'] for p in priv)}/{len(priv)}", "", "| Input | Output | Detected | Result |", "|---|---|---|---|"]
    md += [f"| {p['input']} | {p['output']} | {', '.join(p['detected']) or '—'} | {'✓' if p['ok'] else '✗'} |" for p in priv]
    (RAW_OUTPUTS_DIR / "automated_checks.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\nRaw outputs written to", RAW_OUTPUTS_DIR)

    # overall verdict: every gated check below must pass; retrieval ranking is reported but not gated
    cases = [x["checks"] for x in summary]
    gated = {
        "scenario checks": (sum(c["automated_checks_passed"] for c in cases), sum(c["automated_checks_total"] for c in cases)),
        "expected fields": (sum(c["fields_correct"] for c in cases), sum(c["fields_total"] for c in cases)),
        "claimed-amount paths": (sum(c["ok"] for c in claims), len(claims)),
        "hallucination injection": (sum(h["ok"] for h in hall), len(hall)),
        "privacy redaction": (sum(p["ok"] for p in priv), len(priv)),
    }
    print("\nSUMMARY (" + env_line + ")")
    for name, (ok, total) in gated.items():
        print(f"  {name}: {ok}/{total}")
    print(f"  retrieval probes (reported, not a pass/fail gate): top-1 {sum(r['top1_ok'] for r in retr)}/{len(retr)}, "
          f"top-3 {sum(r['top3_ok'] for r in retr)}/{len(retr)}")
    failed = [n for n, (ok, total) in gated.items() if ok != total]
    print("RESULT: " + (f"FAILED — {', '.join(failed)}" if failed else f"all gated checks passed for {len(cases)}/{len(cases)} scenarios"))
    return 1 if failed else 0


