def _get(case: dict, path: str):
    cur = case
    for part in path.split("."):
        if not isinstance(cur, dict):
            return None
        cur = cur.get(part)
    return cur


def _match(actual, expected) -> bool:
    if isinstance(expected, (int, float)) and not isinstance(expected, bool):
        try:
            return abs(float(actual) - float(expected)) < 0.01
        except (TypeError, ValueError):
            return False
    if isinstance(expected, str):
        return isinstance(actual, str) and expected.strip().lower() in actual.strip().lower()
    return actual == expected


def run_intake(spec: dict, today: date) -> tuple[dict, list[str]]:
    engine = IntakeEngine(new_state(spec["language"]), today=today)
    engine.start()
    engine.handle_user_message(spec["opening_message"])
    unscripted = []
    for _ in range(30):
        q = engine.state.get("pending")
        if not q:
            break
        ans = spec["answers"].get(q)
        if ans is None:
            unscripted.append(q)
            engine.skip_current()
        elif isinstance(ans, dict) and "options" in ans:
            engine.answer_options(q, ans["options"], ans.get("text", ""))
        else:
            engine.handle_user_message(ans)
    return engine.state, unscripted


def transcript_md(state: dict) -> str:
    lines = ["# Intake conversation (raw)", ""]
    for m in state["messages"]:
        who = "**NyayaSetu**" if m["role"] == "assistant" else "**User**"
        lines.append(f"{who}: {m['text']}")
        lines.append("")
    return "\n".join(lines)


def rights_md(r: dict) -> str:
    out = ["# Understand My Rights (raw output)", "", f"_Summary generated by: {r['summary']['generated_by']}_", "", r["summary"]["text"], ""]
    for i in r["issues"]:
        out += [f"## {i['title']}", f"*{i['label_text']} · {i['confidence_text']}*", "", "**What the law says**"]
        for s in i["law"]:
            out.append(f"- {s['short_cite']} — {s['plain']}  \n  Source: {s['url']} (status: {s['status']}, verified {s['verified_on']})")
        out += ["", "**How it may apply**", i["how_applies"], "", "**Evidence you have:** " + (", ".join(i["evidence_have"]) or "—"),
                "**Evidence missing:** " + (", ".join(i["evidence_missing"]) or "—"), "", "**What you can do:** " + i["next_step"], ""]
        if i["uncertain"]:
            out += ["**Uncertain:** " + " | ".join(i["uncertain"]), ""]
    out += ["## Uncertainties", *[f"- {u}" for u in r["uncertainties"]], "", "## When to speak to a lawyer", *[f"- {u}" for u in r["lawyer_triggers"]], ""]
    out += ["## Notices", *[f"- {n['short_cite']}: {n['plain']}" for n in r["notices"]], ""]
    out += ["## Retrieved sources (BM25 ranking, for transparency)", *[f"- {x['id']} ({x['score']})" for x in r["retrieved"]]]
    return "\n".join(out)


def plan_md(plan: list[dict]) -> str:
    out = ["# What should I do next? (raw output)", ""]
    for n, s in enumerate(plan, 1):
        site = s["website"]["label"] + (f" — {s['website']['url']}" if s["website"] and s["website"].get("url") else "") if s["website"] else "—"
        out += [f"## Step {n}: {s['title']}  [{s['status']}]", f"**What to do:** {s['what']}", f"**Why it matters:** {s['why']}",
                f"**Official website:** {site}", "**Evidence to keep:** " + (", ".join(s["evidence"]) or "—"), ""]
    return "\n".join(out)


CLAIM_MISSING_RE = re.compile(r"\[(MISSING: amount you are claiming|अनुपलब्ध: आप कितनी राशि माँग रहे हैं)")


def claim_check(case: dict, docs: dict, expected: dict | None = None) -> dict:
    """Every draft must carry the confirmed refund amount, or a [MISSING] marker — never the price by default."""
    cl = case["claim"]
    paid = case["transaction"].get("amount_paid")
    out = {"actual": {k: cl.get(k) for k in ("amount", "basis", "confirmed", "refund_requested", "is_partial")}, "problems": []}
    if expected is not None:
        out["expected"] = expected
        for k, v in expected.items():
            ok = (cl.get(k) is None) if v is None else _match(cl.get(k), v)
            if not ok:
                out["problems"].append(f"case.claim.{k}: expected {v!r}, got {cl.get(k)!r}")
    full_confirmed = cl.get("confirmed") and cl.get("basis") == "full"
    for name, d in docs.items():
        text = d["text"]
        if cl.get("refund_requested"):
            if cl.get("confirmed") and cl.get("amount"):
                if format_inr(cl["amount"]) not in text:
                    out["problems"].append(f"{name}: confirmed claim {format_inr(cl['amount'])} not in draft")
            elif not CLAIM_MISSING_RE.search(text):
                out["problems"].append(f"{name}: unconfirmed claim but no [MISSING] marker")
        if paid and not full_confirmed and not (cl.get("amount") and abs(cl["amount"] - paid) < 0.5):
            for pat in (f"full amount of {format_inr(paid)}", f"पूरी राशि {format_inr(paid)}", f"Refund {format_inr(paid)}"):
                if pat in text:
                    out["problems"].append(f"{name}: claims the full price without confirmation ('{pat}')")
        if not cl.get("refund_requested") and re.search(r"Refund the full amount|पूरी राशि .* लौटाएँ", text):
            out["problems"].append(f"{name}: asks for a refund the consumer did not request")
    out["ok"] = not out["problems"]
    return out


def check_case(spec: dict, result: dict, extra_docs: dict | None, unscripted: list[str]) -> dict:
    exp = spec["expected"]
    case, rights, docs = result["case"], result["rights"], result["documents"]
    checks = {"id": spec["id"], "unscripted_questions_skipped": unscripted}
    checks["category_expected"] = exp["category"]
    checks["category_actual"] = case["dispute"]["category"]
    checks["category_ok"] = exp["category"] == case["dispute"]["category"]
    field_results = {}
    for path, want in exp.get("fields", {}).items():
        got = _get(case, path)
        field_results[path] = {"expected": want, "actual": got, "ok": _match(got, want)}
    checks["fields"] = field_results
    checks["fields_correct"] = sum(1 for v in field_results.values() if v["ok"])
    checks["fields_total"] = len(field_results)
    all_sources = {sid for i in rights["issues"] for sid in i["source_ids"]}
    checks["sources_cited"] = sorted(all_sources)
    checks["missing_required_sources"] = [s for s in exp.get("must_include_sources", []) if s not in all_sources]
    conf = {i["id"]: i["confidence"] for i in rights["issues"]}
    checks["issue_confidence"] = {k: {"expected": v, "actual": conf.get(k), "ok": conf.get(k) == v} for k, v in exp.get("issue_confidence", {}).items()}
    checks["flags"] = {k: {"expected": v, "actual": case["flags"].get(k), "ok": case["flags"].get(k) == v} for k, v in exp.get("flags", {}).items()}
    if "evidence_must_include" in exp:
        checks["evidence_missing_from_extraction"] = [e for e in exp["evidence_must_include"] if e not in case.get("evidence", [])]
    # citations: every document + every rights explanation must validate against the KB
    kb = get_kb()
    doc_val = {}
    for k, d in {**docs, **(extra_docs or {})}.items():
        doc_val[k] = d["validation"]
    checks["document_validation"] = {k: {"ok": v["ok"], "citations": len(v["citations_found"]), "problems": v["problems"]} for k, v in doc_val.items()}
    rights_text = "\n".join([rights["summary"]["text"]] + [i["how_applies"] + " " + i["next_step"] for i in rights["issues"]])
    rv = validate_text(rights_text, kb=kb)
    checks["rights_text_validation"] = {"ok": rv.ok, "citations": rv.citations_found, "problems": [p.__dict__ for p in rv.problems]}
    checks["all_citations_valid"] = all(v["ok"] for v in doc_val.values()) and rv.ok
    unverified_used = [sid for sid in all_sources if kb.get(sid) and kb.get(sid)["verification_status"] != "verified"]
    checks["non_verified_sources_shown_as_notice_only"] = all(
        i["label"] in ("notice", "procedure") for i in rights["issues"] if any(s in unverified_used for s in i["source_ids"]))
    forbidden = exp.get("documents_must_not_contain", [])
    checks["forbidden_text_found"] = [f"{k}: {s}" for k, d in docs.items() for s in forbidden if s in d["text"]]
    required = exp.get("documents_must_contain", [])
    checks["required_text_missing"] = [s for s in required if not any(s in d["text"] for d in docs.values())]
    if "commission_draft_must_contain" in exp:
        checks["commission_draft_missing_text"] = [s for s in exp["commission_draft_must_contain"] if s not in docs["commission_draft"]["text"]]
    checks["missing_info_count"] = len(case["missing_info"])
    if "min_missing_fields" in exp:
        checks["missing_info_ok"] = len(case["missing_info"]) >= exp["min_missing_fields"]
    if exp.get("lawyer_trigger_expected"):
        checks["lawyer_trigger_ok"] = len(rights["lawyer_triggers"]) >= 2
    if exp.get("uncertainty_expected"):
        checks["uncertainty_shown"] = len(rights["uncertainties"]) > 0
    checks["doc_missing_counts"] = {k: d["missing_count"] for k, d in docs.items()}
    checks["claim_amount"] = claim_check(case, {**docs, **(extra_docs or {})}, exp.get("claim"))
    hard = [checks["category_ok"], not checks["missing_required_sources"], checks["all_citations_valid"],
            all(v["ok"] for v in checks["issue_confidence"].values()), all(v["ok"] for v in checks["flags"].values()),
            not checks["forbidden_text_found"], not checks["required_text_missing"]]
    for key in ("missing_info_ok", "lawyer_trigger_ok", "uncertainty_shown"):
        if key in checks:
            hard.append(checks[key])
    if "commission_draft_missing_text" in checks:
        hard.append(not checks["commission_draft_missing_text"])
    if "evidence_missing_from_extraction" in checks:
        hard.append(not checks["evidence_missing_from_extraction"])
    hard.append(checks["claim_amount"]["ok"])
    checks["automated_checks_passed"] = sum(1 for h in hard if h)
    checks["automated_checks_total"] = len(hard)
    return checks


class FakeLLM(LLMProvider):
    """Simulates a live model so the LLM path and the validator can be tested without an API key."""

    name = "fake-test-llm"
    model = "scripted"
    is_live = True

    def __init__(self, text: str):
        self.text = text

    def complete(self, system, user, max_tokens=800):
        return LLMResponse(text=self.text, provider=self.name, model=self.model)


def hallucination_tests(today: date) -> list[dict]:
    spec = json.loads((ROOT / "tests" / "test_cases.json").read_text(encoding="utf-8"))["cases"][0]
    state, _ = run_intake(spec, today)
    base = run_from_intake(state, today)
    case = base["case"]
    scenarios = [
        ("fabricated_section_and_case_law",
         "Under Section 72A of the Consumer Protection Act, 2019 you are guaranteed a full refund within 7 days [KB:CPA_2_10]. "
         "In Sharma v. ShopKart (2021) the National Commission awarded ₹50,000 for a similar delay.", False),
        ("other_statute_and_promise",
         "The seller has breached the Sale of Goods Act, 1930 and you will definitely get your money back [KB:ECOM_R6_3].", False),
        ("untagged_answer", "You should get a refund because the phone was damaged.", False),
        ("grounded_valid_answer",
         "A product that arrives damaged may be treated as having a 'defect', which you can raise in a complaint [KB:CPA_2_10]. "
         "A marketplace seller must not refuse to take back defective goods or refund you [KB:ECOM_R6_3], but whether your phone counts "
         "as defective depends on your photos and video. It has been about 21 days since you asked, so it is too early to call the delay "
         "an unfair trade practice under Section 2(47)(viii) [KB:CPA_2_47_VIII].", True),
    ]
    out = []
    for name, text, should_pass in scenarios:
        r = RightsAnalyzer(llm=FakeLLM(text)).analyse(case, "en", today)
        used_llm = r["summary"]["generated_by"].startswith("llm:")
        out.append({"scenario": name, "llm_text": text, "expected_accept": should_pass, "accepted": used_llm,
                    "ok": used_llm == should_pass, "note": r["summary"]["note"],
                    "validator": r["summary"].get("llm_validation", {}), "summary_shown": r["summary"]["text"]})
    return out


