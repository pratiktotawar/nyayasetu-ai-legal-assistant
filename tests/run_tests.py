def retrieval_tests() -> list[dict]:
    kb = get_kb()
    out = []
    for q, good in RETRIEVAL_PROBES:
        hits = [r.id for r in kb.search(q, k=3)]
        out.append({"question": q, "acceptable": sorted(good), "top3": hits,
                    "top1_ok": bool(hits) and hits[0] in good, "top3_ok": any(h in good for h in hits)})
    return out


