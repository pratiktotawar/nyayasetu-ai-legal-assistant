def claim_path_tests(today: date) -> list[dict]:
    out = []
    for name, story, lang, answers, (amt, basis, confirmed), times in CLAIM_PATHS:
        eng = IntakeEngine(new_state(lang), today=today)
        eng.start()
        eng.handle_user_message(story)
        queue, asked, reask_msg = list(answers), 0, False
        for _ in range(40):
            q = eng.state.get("pending")
            if not q:
                break
            if q == "desired_resolution":
                eng.answer_options(q, ["refund"])
            elif q == "claim_amount":
                asked += 1
                eng.handle_user_message(queue.pop(0) if queue else "skip")
                last = eng.state["messages"][-1]["text"]
                reask_msg = reask_msg or ("couldn't tell the exact amount" in last or "सटीक राशि नहीं समझ" in last)
            elif q == "issue_details":
                eng.handle_user_message("It was damaged.")
            else:
                eng.skip_current()
        res = run_from_intake(eng.state, today, lang=lang)
        cl = res["case"]["claim"]
        cc = claim_check(res["case"], res["documents"])
        ok = ((cl["amount"] is None) if amt is None else _match(cl["amount"], amt)) and cl["basis"] == basis \
            and cl["confirmed"] == confirmed and asked == times and cc["ok"] and (reask_msg if times == 2 else True)
        relief = [ln.strip() for ln in res["documents"]["platform_complaint"]["text"].splitlines()
                  if re.match(r"^\d+\.\s+(Refund|Deliver|.*लौटाएँ)", ln.strip())]
        out.append({"path": name, "answers": answers, "times_asked": asked, "reasked_with_message": reask_msg,
                    "claim": {k: cl[k] for k in ("amount", "basis", "confirmed", "is_partial")}, "relief_line": relief[:1],
                    "draft_problems": cc["problems"], "ok": bool(ok)})
    return out


